let 어긋남 = 0;
for (const [목표, 경우들] of 모음) {
  console.log('\n' + 목표);
  for (const [이름, 들린, 통과해야] of 경우들) {
    const s = similarity(목표, 들린);
    const 통과 = s >= 70;
    const 맞나 = 통과 === 통과해야;
    if (!맞나) 어긋남++;
    console.log('   ' + String(s).padStart(3) + '점  ' + (통과 ? '통과 ' : '재연습') +
      '  ' + (맞나 ? '    ' : ' ←! ') + 이름);
  }
}
console.log('\n뜻대로 안 나온 경우: ' + 어긋남 + '개  (통과 기준 70점)');

/* 한자로 받아적혀도 제 점수가 나와야 합니다 */
let 통과수 = 0, 실패수 = 0;
function 확인(n, ok) { ok ? (통과수++, console.log('  ok   ' + n)) : (실패수++, console.log('  FAIL ' + n)); }
console.log('\n한자로 받아적혀도 괜찮은가');
확인('図書館 = としょかん', similarity('としょかんですか。', '図書館ですか') >= 95);
확인('本屋・左 도 읽어 냄', similarity('としょかんは ほんやの ひだりに あります。', '図書館は本屋の左にあります') >= 95);
확인('有ります 같은 표기도', similarity('としょかんは ほんやの ひだりに あります。', '図書館は 本屋の 左に 有ります') >= 95);

console.log('\n선 지키기 — 아무 말이나 통과하면 연습이 안 됩니다');
확인('정확히 읽으면 만점', similarity('としょかんですか。', 'としょかんですか。') === 100);
확인('전혀 다른 말은 떨어진다', similarity('としょかんですか。', 'ありがとう') < 70);
확인('침묵은 0점', similarity('としょかんですか。', '') === 0);

console.log('\n통과 ' + 통과수 + ' / 실패 ' + 실패수);
process.exit((실패수 || 어긋남) ? 1 : 0);
