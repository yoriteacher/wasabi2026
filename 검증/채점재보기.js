const 조각 = 글.slice(글.indexOf('/* ---------- 유사도 ----------'), 글.indexOf('function buildDiff'));
const similarity = new Function(조각 + '\nreturn similarity;')();

/* 실제 연습 문장 + 한국 학생이 흔히 내는 어색함 */
